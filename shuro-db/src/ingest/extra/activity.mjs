/**
 * ソース由来の文字列を掃除する。
 * 北海道PDFは列がずれると「日給＋時給 その他サービス・役務」「73,257.1 清掃・施設管理」の
 * ように支払形態や金額が前置してしまうため、それを剥がす。
 */
export function cleanActivityLabel(raw) {
  let t = String(raw ?? '').trim();
  if (!t) return null;
  t = t.replace(/^(?:[\d,]+(?:\.\d+)?)\s+/, '');                       // 先頭の金額
  t = t.replace(/^(?:月給|日給|時給|出来高|時間給)(?:＋(?:月給|日給|時給|出来高))*\s*/, ''); // 支払形態
  t = t.trim();
  return t || null;
}

/** 統一分類に写像する。対応表に無いものは null（勝手に分類しない）。 */
export function toCategory(raw) {
  const t = cleanActivityLabel(raw);
  if (!t) return null;
  return MAP.get(t) ?? null;
}

/** 未対応の表記を集計するため、掃除後のラベルも返す */
export function classify(raw) {
  const label = cleanActivityLabel(raw);
  return { label, category: label ? (MAP.get(label) ?? null) : null };
}
